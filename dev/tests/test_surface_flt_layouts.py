def _load(tmp_path: Path, data: bytes, sidecar: str = "") -> tuple:
    (tmp_path / "Surface.flt").write_bytes(data)
    if sidecar:
        (tmp_path / "Surface.flt.md").write_text(sidecar, encoding="utf-8")
    surface_flt.load_folder.cache_clear()
    return surface_flt.load_folder(tmp_path)


def _at(recs, x, y):
    """사진 X·Y 에서 앱과 같은 규칙(5 µm 안 가장 가까운 레코드)으로 고른 레코드."""
    return geometry._nearest(recs, (x, y), geometry.GEOMETRY_MATCH_TOL)


def test_120_record_file_decodes_with_old_layout(tmp_path):
    recs = _load(tmp_path, _FLT_120)
    assert len(recs) == 3
    # (사진 이름, ini X, ini Y) → (area, BlobBreadth, BlobFeretMax, zone)
    for x, y, area, br, fm, zone in [
        (91179.6739833027, 281903.393160028, 307.0, 7.75691, 37.06245, 1),   # 91187.281918.c.2133359845.jpeg
        (91202.4259791757, 281928.420354533, 26.0, 3.48132, 7.69133, 1),    # 91207.281943.c.1307085361.jpeg
        (94678.4849096198, 151456.48917107, 16.0, 2.90336, 5.46089, 2),     # 94686.151464.c.735978651.jpeg
    ]:
        r = _at(recs, x, y)
        assert r is not None
        assert r.area == area and abs(r.blob_breadth - br) < 1e-5
        assert abs(r.blob_feret_max - fm) < 1e-5
        assert r.zone == zone and r.contrast == 0.0
        assert r.recipe is None          # 120 레이아웃엔 recipe 칸이 없다


